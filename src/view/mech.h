// Шагающие машины в кадре: «Вежа» (docs/vezha.md), «Тать» (docs/tat.md) и двуногая «Гридь» (docs/gryd.md) — машины
// из жёстких частей на костях.
// Вся их жизнь — у вида: где стоят, куда идут, как ставят лапы, куда смотрят. Шаг мира о них пока не знает
// (таблица машин, приказы и попадания — следующий заход); место даёт строка сцены `prop vezha …` или `prop tat …`,
// вид перехватывает её и ведёт машину сам. Движение — расчётом, а не захватом: ноги решаются по опоре (IK), тело —
// пружинами, шаги — по правилам походки, поэтому машина ходит по любому рельефу и в любую сторону
#pragma once
#include "../render/render.h"
#include "../sim/extract.h"

struct ViewAssets;
struct ViewInput;

constexpr u32 MECH_MAX = 4;     // машин в кадре
constexpr u32 MECH_LEGS = 4;

// Вид машины: своя сетка и скелет, свои размеры (MechDesc в mech_in.h) и своё поведение
enum MechKind : u8 { MECH_VEZHA = 0, MECH_TAT, MECH_GRYD, MECH_KINDS };
// Состояния: общие (лежит, встаёт, стоит, идёт, ложится), у Тати — лёжка для выстрела, у Гриди — стрельба с колена
// (выпад, винтовка у плеча, очереди)
enum MechState : u8 { MECH_PACKED = 0, MECH_UNFOLD, MECH_STAND, MECH_WALK, MECH_FOLD, MECH_PRONE, MECH_AIM };
// Принудительный режим (--mech): сама, лежит, стоит на месте, обходит без складывания, показ — по порядку всё, что
// машина умеет, по кругу
enum MechDemo : u8 { MECH_DEMO_AUTO = 0, MECH_DEMO_PACK, MECH_DEMO_STAND, MECH_DEMO_WALK, MECH_DEMO_SHOW };
// Плюсна: параллельна бедру (пантограф, нога решается двумя длинами L1 + L3 и L2) или отвесна в осях рамы
// (нога решается двумя длинами L1 и L2 до голеностопа над лапой; у Вежи — стойка голеностопа паучьей ноги)
enum MechLegMode : u8 { MECH_LEG_PAR = 0, MECH_LEG_VERT };

struct MechLeg {
    WPos at;          // точка опоры лапы на земле
    WPos from, to;    // шаг: откуда и куда
    Vec3 n;           // нормаль опоры
    f32 t;            // < 0 — стоит; 0..1 — в шаге
    f32 dur, lift;    // длительность шага, с; высота дуги, м
    f32 fold;         // 1 — сложена у рамы, 0 — работает
    Vec3 pol;         // начало пути складывания у земли в осях рамы: поворот бедра, вынос от оси поворота, высота
    f32 yaw, yaw_to;  // курс ступни в мире (ноги в плоскости, MechLegDesc::plane): стоит — держит, в шаге — к yaw_to
};

struct Mech {
    bool live;
    u8 kind;          // MechKind
    u32 prop;         // место объекта сцены + 1
    u32 copy;         // копия сетки (render_skinned_create)
    u32 rng;
    WPos home;        // место машины
    f32 home_yaw;
    // Тело
    WPos at;          // середина; y — сглаженная опора под лапами
    f32 yaw, yaw_v;   // курс рамы, рад
    Vec3 vel, acc;    // скорость и сглаженное ускорение в мире (y = 0)
    f32 h, h_v, h_to; // оси бёдер над опорой, м
    f32 pitch, pitch_v, roll, roll_v;   // наклон рамы
    f32 hull, hull_v; // корпус (у Тати — станок винтовки) относительно рамы
    f32 gun, gun_v;   // возвышение ствола
    f32 eye, eye_to, eye_wait;          // голова-прибор относительно корпуса (у Тати — относительно рамы)
    f32 ant[2][2], ant_v[2][2];         // антенны: качание вокруг x и z
    MechLeg leg[MECH_LEGS];
    f32 lag;          // насколько самая отставшая лапа перебрала свой порог шага (1 — пора шагать)
    // Поведение
    u8 state;
    f32 state_t;      // секунд в состоянии
    f32 wait;         // сколько ещё стоять (лежать)
    u32 points_left;  // точек обхода до возвращения домой
    WPos goal;
    bool goal_home;
    f32 speed_max;
    f32 look, look_wait;   // куда смотрит без цели (курс в мире) и когда выберет заново
    f32 mood_t;       // сколько держать необычную высоту (привстала, присела)
    u8 jump;          // прыжок на рывке: 0 — нет, 1 — приседает, 2 — толчок (лапы ещё на земле), 3 — летит
    bool leap;        // на этом отрезке пути прыгнет
    f32 jump_t;       // сколько ещё приседать
    u8 show;          // шаг показа (--mech show)
    f32 clock;
    // Тать (docs/tat.md): походка, лёжка, выстрел, морок
    u8 gait;          // 0 — крадётся (по одной ноге), 1 — перебежка (парами перед / зад)
    u8 next_leg;      // чья очередь шагать крадучись
    f32 creep_t;      // Вежа шагом: сколько ещё переносить вес до отрыва следующей лапы
    Vec3 sway, sway_v;   // сдвиг тела над опорой в осях рамы (переносит вес с шагающей ноги)
    f32 stow, stow_to;   // по-походному: 0 — голова и ствол свободны, 1 — убраны по курсу
    f32 kick, kick_v;    // отдача: откат тела назад, м
    u32 shots;        // выстрелов за лёжку
    f32 aim_t;        // сколько ещё целиться до выстрела
    f32 veil, veil_to;   // морок: 0 — видна, 1 — почти не видна
    bool aim_on;      // есть цель лёжки
    WPos aim;         // куда целится в лёжке
    // Гридь (docs/gryd.md): выпад и стрельба очередями
    f32 burst_t;      // до следующего выстрела очереди, с
    u32 bursts;       // очередей за стрельбу
    u8 burst_left;    // выстрелов в очереди осталось
    u8 lead;          // какая нога выносится вперёд в выпаде (1 — левая)
    f32 gun_yaw;      // винтовка внутрь от оси (по-походному), рад
    f32 flash, flash_roll;   // вспышка выстрела у дульного тормоза: 1 — в миг выстрела, гаснет за 50 мс; поворот вокруг ствола
};

// Нога вида машины — из скелета (бинд-поза) и описания вида
struct MechLegRig {
    i32 bone[11];     // бедренный узел, бедро, голень, плюсна, лапа, цилиндр и шток подъёма бедра, колена и плюсны
                      // (у ноги без цилиндра — −1)
    Vec3 corner;      // ось поворота бедра от оси машины
    Vec3 dir;         // куда нога смотрит в бинде
    f32 u, l1, l2, l3;    // вынос оси качания, длины звеньев
    f32 a1, a2, a3;   // углы бедра, голени и плюсны к горизонту в бинде
};

// Рука, держащая оружие (Гридь): плечо, предплечье, кисть и цилиндр локтя. Запястье ставится туда, где его держит
// винтовка (кисть повёрнута как винтовка), локоть — решение двумя длинами к полюсу
struct MechArmRig {
    i32 ua, fa, hand, ea, eb;
    f32 la, lb;       // плечо и предплечье
    Vec3 pole;        // полюс локтя в бинде (оси сетки)
};

struct MechRig {
    bool bound, failed;
    u32 body;         // тело в ViewAssets::bodies
    i32 chassis, hull, gun, eye, ant[2];   // у Тати hull — станок винтовки
    MechLegRig leg[MECH_LEGS];
    MechArmRig arm[2];                     // у Гриди: правая, левая; у других — кости −1
    i32 cyl[12][2];                        // цилиндры: гильза и шток смотрят друг на друга
    u32 ncyl;
    i32 flash;                             // вспышка выстрела (Гридь): кость у дульного тормоза, сжата в точку, пока не стреляет
};

struct MechView {
    MechRig rig[MECH_KINDS];
    Mech mech[MECH_MAX];
    u8 demo;
    bool veil_demo;   // --mech veil: стоит, морок по кругу (только у Тати)
    bool prone_demo;  // --mech prone: лёжка и выстрелы (только у Тати)
    bool aim_demo;    // --mech aim: выпад и очереди без конца (только у Гриди)
    i8 pick;          // за какой машиной камера и след (--mech-kind): вид или −1 — первая
};

void mech_view_init(MechView &mv);
// Режим по слову ключа --mech (pack, stand, walk, show; у Тати veil — морок по кругу, prone — лёжка; у Гриди aim —
// выпад и очереди); false — слово не то
bool mech_view_demo(MechView &mv, const char *name);
// Вид для --mech-kind (vezha, tat, gryd); false — слово не то
bool mech_view_pick(MechView &mv, const char *name);
// Объект сцены с этой сеткой — место машины, а не статичная деталь: вид машины или −1
i32 mech_view_kind(u64 mesh_name);
// Опора камеры плавно идёт за выбранной машиной (--mech-follow): только x и z, высоту держит камера
void mech_view_follow(const MechView &mv, WPos &pivot, f32 dt);
// Сообщить место (каждый кадр, из выписки объектов): prop — номер места объекта, kind — mech_view_kind
void mech_view_place(MechView &mv, u32 prop, u8 kind, const WPos &at, Turn yaw);
// Машины кадра: экземпляры (inst, ni — дописывает, места — MECH_MAX), палитры и скиннинг — в out
void mech_view_build(MechView &mv, const ViewAssets &assets, const ViewInput &in, Arena &frame, RenderInstance *inst,
                     u32 &ni, RenderFrame &out);
// След движения без окна (--mech-trace): кадр жизни выбранной машины на dt секунд и строка чисел — состояние, место,
// углы и точки костей в метрах от дома. Скелеты видов даёт вызывающий (тела и GPU не нужны), skels[kind]
struct Skel;
bool mech_view_trace(MechView &mv, const Skel *skels, const Extract &c, f32 dt, char *line, usize cap);
// Имя сетки (и скелета) вида
const char *mech_kind_name(u8 kind);
