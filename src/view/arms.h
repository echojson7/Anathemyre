// Оружие на теле и в руках (docs/arms.md): где оружие в кадре и что делают руки. Убрано — висит на ремне у бедра
// или за спиной, жёстко за костью; в бою — в кисти (пальцы сжаты, оружие жёстко за кистью) или в стойке двумя
// руками; достать и убрать — кисть тянется к месту ношения (IK руки). Только вид: шаг мира знает лишь цель боя и
// действие, повтор этого не видит
#pragma once
#include "../anim/clip.h"
#include "../anim/pose.h"
#include "weapon.h"

// Как оружие держат и носят. Оси сетки оружия: начало — середина кулака верхней руки (у гарды), остриё — +Y,
// лезвие — +X. Числа — y по оси сетки, м
struct WeaponHold {
    u8 hands;      // 1 — одной рукой, 2 — двумя, 3 — древко
    u8 carry;      // CARRY_*: у левого бедра, за спиной наискось, за спиной почти отвесно
    f32 grip2;     // вторая кисть (пока не используется: в клипах CMU вторая кисть там, где была у актёра)
    f32 carry_at;  // точка оси, за которую оружие висит на ремне
    f32 tip, butt; // остриё и навершие
};

constexpr u32 ARMS_FINGERS = 15;  // кости пальцев кисти: 5 пальцев по 3
constexpr u32 ARMS_STANCE = 12;   // кости стойки, кроме первого позвонка: позвонки 2–3, шея, голова, ключицы, руки

// Привязка к скелету: кости, хват, стойка, места ношения. Считается раз
struct ArmsBind {
    bool ok;
    i32 pelvis, spine1, chest;
    i32 clav[2], upper[2], lower[2], hand[2];  // 0 — левая, 1 — правая
    i32 finger[2][ARMS_FINGERS];
    Quat curl[2][ARMS_FINGERS];  // местный поворот кости пальца в сжатой кисти
    Vec3 palm[2];                // середина ладони (ось рукояти) в осях кости кисти
    Quat grip_q;                 // оружие в правой кисти: поворот в осях кости кисти
    Quat wrist_low;              // доворот правой кисти к мизинцу: клинок вперёд-вниз, когда рука опущена
    i32 stance_bone[ARMS_STANCE];
    Quat stance_rot[ARMS_STANCE];  // местные повороты стойки (ключ клипа с оружием)
    Quat stance_spine;             // первый позвонок стойки в осях корня: верх тела не ходит за тазом
    Quat stance_weapon;            // оружие в стойке (по линии ладоней её позы) в осях груди
    Quat rest_arm[4];              // правая рука у бедра (покой): ключица, плечо, предплечье, кисть
    Quat pelvis_unbind, chest_unbind;  // бинд⁻¹ костей мест ношения
    Vec3 pelvis_at, chest_at;          // их головы в бинде
};

// Состояние у человека (вид)
struct ArmsLook {
    f32 t;     // 0 — убрано, 1 — в руке; между — достаёт или убирает
    f32 calm;  // сколько секунд без боя (убирает не сразу)
};

// Доли на кадр из состояния
struct ArmsState {
    bool held;  // оружие в кисти (после захвата)
    f32 s;      // 0 — у места ношения, 1 — в рабочем положении (после захвата)
    f32 reach;  // кисть тянется к месту ношения
    f32 fist;   // правая кисть сжата
    f32 stance; // доля стойки по скорости (без перехода)
    f32 two;    // стойка: хват двумя руками вне действий
    f32 one;    // оружие в одной правой руке, рука опущена (на ходу)
};

// Привязка: стойка — клип stance в момент stance_t, рука у бедра — клип rest в момент rest_t. false — нет костей
bool arms_bind(ArmsBind &b, const Skel &s, const AnimClip &stance, f32 stance_t, const AnimClip &rest, f32 rest_t);
// Шаг состояния: fight — человек в бою (цель, действие, реакция), urgent — действие уже идёт (достать быстро),
// fresh — человека в прошлом кадре не было (без перехода)
ArmsState arms_update(ArmsLook &L, const WeaponHold &h, bool fight, bool urgent, f32 speed, f32 dt, bool fresh);
// Стойка и рука с оружием поверх ходьбы, до клипов действий. wr — поза до правки (pose_world)
void arms_pose_hold(const ArmsBind &b, const ArmsState &a, Quat *rot, const Quat *wr);
// После всей позы: кисть к месту ношения, пальцы, место и поворот оружия в осях сетки человека. act_any, act_two,
// act_block — веса клипа действия: любого, с оружием (хват двумя руками, как в дорожках шага мира), блока.
// rot, wr, wp — поза (wr, wp пересчитаны на выходе)
struct ArmsWeapon {
    Vec3 at;
    Quat q;
};
ArmsWeapon arms_pose_weapon(const ArmsBind &b, const Skel &s, const WeaponHold &h, const ArmsState &a, f32 act_any,
                            f32 act_two, f32 act_block, i32 trans_bone, const Vec3 *trans, Quat *rot, Quat *wr, Vec3 *wp);
