// Небо в кадре (docs/sky.md): из часов мира (выписка) — солнце, луна с фазой и поворот звёздного неба, из
// data/sky.txt — слои воздуха. Только кадр: на шаг мира не влияет, float и libm здесь разрешены
#pragma once
#include "../render/render.h"
#include "../sim/world.h"

// Параметры неба (data/sky.txt). Числа — в единицах файла, перевод в физические — sky_build
struct SkyDesc {
    f32 latitude = 35.0f;      // градусы
    f32 season = 12.0f;        // склонение солнца, градусы (0 — равноденствие, 23.4 — летнее солнцестояние)
    f32 moon_age = 10.0f;      // возраст луны в день 0, сутки (0 — новолуние, 14.8 — полнолуние)
    f32 sun = 3.2f;            // освещённость от солнца над атмосферой (единицы кадра)
    f32 moon_boost = 1.0f;     // множитель лунного света (1 — как в жизни)
    f32 moon_albedo = 0.12f;
    f32 rayleigh = 1.0f;       // множитель газа (синева неба)
    f32 mie = 1.0f;            // множитель пыли высокого слоя
    f32 mie_g = 0.8f;
    f32 haze = 0.10f;          // рассеяние нижней дымки на уровне моря, 1/км
    f32 haze_height = 900.0f;  // высота её слоя, м
    f32 haze_tint[3] = {0.92f, 0.84f, 0.70f};  // доля рассеяния в ослаблении по каналам: пыль желтит даль
    f32 ozone = 1.0f;
    f32 alt0 = 0.0f;           // высота нуля карты над уровнем моря, м
    f32 ground[3] = {0.30f, 0.26f, 0.21f};  // альбедо планеты (отсвет снизу)
    f32 stars = 1.0f;
    f32 night_glow = 0.6f;     // свечение ночного неба, миллионные освещённости солнца
    f32 exposure = 1.0f;
    f32 adapt = 0.75f;         // насколько глаз привыкает к темноте: 0 — никак, 1 — полностью
    f32 exposure_ref = 3.0f;   // освещённость, при которой множитель экспозиции = exposure
    f32 night_blue = 0.55f;    // синева и серость ночью
    f32 sky_gain = 2.0f;       // множитель рассеянного света неба: одно рассеяние с таблицей многократного
                               // даёт небо темнее настоящего в 2–3 раза (нет полной оптики пыли)
    // Воздух пустыни: те же величины, вид смешивает их с воздухом выше по маске пустыни под камерой
    f32 desert_mie = 1.0f;
    f32 desert_haze = 0.10f;
    f32 desert_haze_height = 900.0f;
    f32 desert_haze_tint[3] = {0.92f, 0.84f, 0.70f};
    f32 desert_ground[3] = {0.30f, 0.26f, 0.21f};
};

// Разобрать data/sky.txt поверх значений по умолчанию. false — ошибка, текст в err (с номером строки)
bool sky_parse(SkyDesc &d, const u8 *text, usize size, char *err, usize err_cap);

// Часы между двумя выписками: тики как f64 (интерполяция по alpha; скачок часов — без протяжки)
f64 sky_clock_ticks(const Clock &prev, const Clock &cur, f32 alpha);
// Час дня 0..24 для заголовка окна
f32 sky_hour(const Clock &c, f64 ticks);

// Небо кадра и временный главный свет (солнце или луна). desert — доля воздуха пустыни 0..1 (маска под
// камерой), cam_y — высота глаза от нуля карты, м
void sky_build(const SkyDesc &desc, f32 desert, const Clock &clock, f64 ticks, f32 cam_y, RenderSky &out, RenderLight &key);
