// Небо в кадре (docs/sky.md): из часов мира (выписка) — солнце, луна с фазой и поворот звёздного неба, из
// data/sky.txt — слои воздуха. Только кадр: на шаг мира не влияет, float и libm здесь разрешены
#pragma once
#include "../render/render.h"
#include "../sim/world.h"

// Параметры неба (data/sky.txt). Числа — в единицах файла, перевод в физические — sky_build
struct SkyDesc {
    f32 latitude = 35.0f;      // градусы
    f32 season = 12.0f;        // склонение солнца, градусы (0 — равноденствие, 23.4 — летнее солнцестояние)
    f32 moon_age = 10.0f;      // возраст луны в день 0, сутки (0 — новолуние, 14.8 — полнолуние)
    f32 sun = 128000.0f;       // освещённость от солнца над атмосферой, лк
    f32 moon_boost = 1.0f;     // множитель лунного света (1 — как в жизни)
    f32 moon_albedo = 0.12f;
    f32 rayleigh = 1.0f;       // множитель газа (синева неба)
    f32 mie = 1.0f;            // множитель пыли высокого слоя
    f32 mie_g = 0.8f;
    f32 haze = 0.10f;          // рассеяние нижней дымки на уровне моря, 1/км
    f32 haze_height = 900.0f;  // высота её слоя, м
    f32 haze_tint[3] = {0.92f, 0.84f, 0.70f};  // доля рассеяния в ослаблении по каналам: пыль желтит даль
    f32 ozone = 1.0f;
    f32 alt0 = 0.0f;           // высота нуля карты над уровнем моря, м
    f32 ground[3] = {0.30f, 0.26f, 0.21f};  // альбедо планеты (отсвет снизу)
    f32 stars = 1.0f;
    f32 night_glow = 0.6f;     // свечение ночного неба, миллионные освещённости солнца
    f32 exposure_ev = 0.0f;    // поправка экспозиции, EV (+1 — вдвое светлее)
    f32 adapt = 0.75f;         // насколько глаз привыкает к темноте: 0 — никак, 1 — полностью
    f32 exposure_ref = 100000.0f;  // освещённость земли «нормы», лк: при ней поправка не нужна
    f32 adapt_dark = 3.0f;     // время привыкания к темноте, с
    f32 adapt_light = 1.0f;    // к свету, с
    f32 night_blue = 0.55f;    // синева и серость ночью
    // Местная экспозиция (docs/light.md): колено, стопы от среднего серого; наклон дальше него в свет и в тень
    f32 local_tone[3] = {1.0f, 0.05f, 1.0f};
    // Замер и цвет глаза (docs/light.md): доля замера по свету мест в кадре (0 — только у камеры); доля привыкания к
    // цвету света (баланс белого, 0 — выкл); время привыкания к цвету, с
    f32 meter_view = 0.8f;
    f32 white_balance = 0.8f;
    f32 adapt_color = 1.5f;
    f32 sky_gain = 1.0f;       // множитель рассеянного света неба (1 — как считает модель атмосферы)
    f32 sun_size = 0.53f;      // видимый диаметр диска солнца, градусы (настоящий 0.53; свет и тени от него не зависят)
    f32 moon_size = 0.52f;     // видимый диаметр диска луны, градусы
    f32 halo = 0.5f;           // доля пыли, что светит узко вперёд: ореол у светила (0 — без него)
    f32 halo_g = 0.96f;        // насколько узок ореол
    f32 night_dark = 0.0f;     // ночь темнее привыкания глаза, EV
    f32 night_fill = 1.0f;     // свечение ночного неба на землю: во сколько раз сильнее видимого в кадре
    f32 adapt_night = 0.3f;    // степень привыкания ниже света полной луны: темнее луны — заметно темнее в кадре
    f32 milky = 1.0f;          // яркость Млечного пути
    f32 twinkle = 1.0f;        // мерцание звёзд
    f32 glare = 0.0f;          // блеск: доля света ярких мест, что глаз рассеивает вокруг (docs/glare.md)
    // Объектив (docs/lens.md): силы эффектов камеры, включает их меню (Esc → Графика → «Камера»)
    f32 lens_flare = 0.0f;     // блики солнца в линзах: множитель долей отражения (1 — просветлённый объектив)
    f32 lens_ca = 0.0f;        // хроматическая аберрация: сдвиг крайних длин волн в углу кадра, доля полудиагонали
    f32 lens_vignette = 0.0f;  // виньетка: доля закона cos⁴
    f32 film_grain = 0.0f;     // зерно плёнки: разброс в средних тонах, доля шкалы экрана
    // Облака (docs/clouds.md)
    f32 clouds = 0.0f;         // доля неба под кучевыми: 0 — нет
    f32 cloud_base = 2400.0f;  // низ кучевых, м над уровнем моря
    f32 cloud_top = 4200.0f;   // верх самых высоких
    f32 cloud_density = 1.0f;  // плотность (1 — как у кучевых хорошей погоды)
    f32 cloud_light = 1.0f;    // яркость облаков (множитель рассеянного в них света)
    f32 cirrus = 0.0f;         // доля неба под перистыми: 0 — нет
    f32 cirrus_height = 9500.0f;
    f32 wind = 8.0f;           // ветер на высоте облаков, м/с
    f32 wind_dir = 250.0f;     // куда он несёт облака, градусы от севера по часовой
    // Воздух у земли (docs/air.md): пыль, в которой видны лучи солнца за предметами и свет огней
    f32 air_dust = 0.0f;           // рассеяние и поглощение пыли у нуля карты, 1/км (0 — нет)
    f32 air_dust_height = 30.0f;   // высота её слоя, м
    f32 air_tint[3] = {0.9f, 0.86f, 0.8f};  // доля рассеяния по каналам (остальное пыль поглощает)
    f32 air_g = 0.8f;              // лепесток вперёд: пыль светит к источнику
    f32 air_iso = 0.3f;            // доля рассеяния во все стороны
    // Воздух пустыни: те же величины, вид смешивает их с воздухом выше по маске пустыни под камерой
    f32 desert_air_dust = 0.0f;
    f32 desert_mie = 1.0f;
    f32 desert_haze = 0.10f;
    f32 desert_haze_height = 900.0f;
    f32 desert_haze_tint[3] = {0.92f, 0.84f, 0.70f};
    f32 desert_ground[3] = {0.30f, 0.26f, 0.21f};
};

// Разобрать data/sky.txt поверх значений по умолчанию. false — ошибка, текст в err (с номером строки)
bool sky_parse(SkyDesc &d, const u8 *text, usize size, char *err, usize err_cap);

// Часы между двумя выписками: тики как f64 (интерполяция по alpha; скачок часов — без протяжки)
f64 sky_clock_ticks(const Clock &prev, const Clock &cur, f32 alpha);
// Час дня 0..24 для заголовка окна
f32 sky_hour(const Clock &c, f64 ticks);

// Небо кадра и временный главный свет (солнце или луна). desert — доля воздуха пустыни 0..1 (маска под
// камерой), cam_y — высота глаза от нуля карты, м
// cloud_time — время облаков, с (ветер и смена формы; время кадра, не часы мира)
void sky_build(const SkyDesc &desc, f32 desert, const Clock &clock, f64 ticks, f32 cam_y, f64 cloud_time, RenderSky &out,
               RenderLight &key);
