// Карта мира: одна поверхность 28×28 км из зерна. Крупный рельеф (увалы, котловины, гряды) — сетка
// MAP_STEP с плавной выборкой, мелкий (дюны) — шумом в каждой точке. В центре лагерь (зал, арена, Скудель)
// на прежнем рельефе, к востоку долина у реки (valley.h). Одна высота для ног и для рендера (без построек)
#ifndef ANA_MAP_H
#define ANA_MAP_H

#include "../core/arena.h"
#include "../core/math3d.h"

#define MAP_HALF 14000.0f   // от центра до края карты, м
#define MAP_STEP 16.0f      // шаг сетки крупного рельефа, м

// Крупный рельеф из зерна (по потокам). До вызова map_height считает без него
bool map_init(Arena *perm, u64 seed);
// Высота земли без построек
f32  map_height(f32 x, f32 z);
// Доля долины в точке: 1 — долина, 0 — пустошь; между ними склоны сходят в дюны
f32  map_valley(f32 x, f32 z);
// Цвет земли RGBA8: альбедо (линейное) и вид поверхности в альфе (0 — песок, 1 — земля долины)
u32  map_color(f32 x, f32 z, f32 h);
// Узлы w×h с шагом step от (x0, z0), строками по Z: высота и цвет. Для рельефа рендера (render_set_terrain)
void map_fill(f32 x0, f32 z0, f32 step, u32 w, u32 h, f32 *height, u32 *color, void *user);

#endif
