// Действия людей и удар (этап 10, docs/people.md «Удар»): действие — запись данных (data/actions/*.txt) поверх
// клипа и его меток. Шаг мира ведёт его по запечённой дорожке клипа (.trk) без смешивания: корень, капсулы тела
// и отрезок клинка на тик. Попадание — клинок против 11 капсул другого человека в окне удара; стоп на попадании
// (hit-stop) — замершие тики у обоих; реакция задетого — отброс и замирание движения
#pragma once
#include "../anim/track.h"
#include "../core/mathf.h"
#include "../core/wpos.h"

constexpr u32 ACTIONS_MAX = 8;
constexpr u32 BODY_PARTS = 11;   // как PARTS в tools/retarget/bake.py
constexpr u32 PART_CHEST = 1;
constexpr u8 ACTION_NONE = 0xFF;
constexpr f32 ACTION_GUARD_GAP = 0.4f;  // м: зазор дистанции между ударами сверх наибольшей досягаемости
constexpr f32 ACT_BLOCK_FACE = 1.2f;    // блок держит удар, если бьющий не дальше стольких рад от лица (и ИИ так судит)

// Вид действия (этап 11): удар, блок, уклон. Удар бьёт клинком в окне hit; блок и уклон защищают в окне block клипа
enum ActionKind : u8 { ACT_STRIKE = 0, ACT_BLOCK = 1, ACT_DODGE = 2 };
// Линии удара: куда идёт клинок (сверху, сбоку на уровне груди и головы, по ногам). У защиты — какие линии она
// закрывает (блок — шанс навыками и RNG мира; уклон — подсказка ИИ, увёл ли тело от клинка — решают капсулы)
enum ActionLine : u8 { LINE_OVER = 1, LINE_SIDE = 2, LINE_LOW = 4 };

struct ActionDesc {
    u64 name;                // хеш имени файла без .txt
    char label[24];
    u8 kind;                 // ActionKind
    u64 clip;                // хеш имени клипа
    char clip_name[32];
    const Track *track;      // дорожка клипа на скелете game_engine
    u16 start;               // тик клипа, с которого действие начинается (start, ключ ×2): тики действия — тики клипа
    u16 end;                 // тик конца действия (end, ключ ×2)
    u16 cancel;              // с какого тика можно отменить (метка cancel клипа); 0xFFFF — нельзя
    u16 hit_a, hit_b;        // удар: окно удара, тики клипа (метка hit, ключи ×2), включительно
    u16 guard_a, guard_b;    // защита: окно блока или уклона (метка block клипа)
    u8 line;                 // удар: ActionLine; защита: закрываемые линии (маска)
    f32 reach_min, reach_max;  // удар: начинать, когда до цели столько, м
    u8 hitstop;              // удар: тиков стопа на попадании у обоих; блок — на отбитом ударе
    f32 push;                // удар: отброс задетого, м; блок — отброс отбитого бьющего
    u16 react;               // удар: тиков реакции задетого; блок — тиков, пока отбитый бьющий не может бить
    f32 chance, chance_skill;  // блок: доля отбитых при равных навыках и прибавка на единицу разницы навыков
    Turn aim;                // удар: куда идёт клинок в середине окна удара в осях начала действия (корень клипа
                             // поворачивается по ходу удара): бьющий встаёт так, чтобы цель была по aim
};

// Описания действий и дорожки ходьбы и бега (капсулы того, кто не в действии). Неизменны после создания мира,
// хеш — в хеше неизменного (world_static_hash)
struct ActionTable {
    ActionDesc a[ACTIONS_MAX];
    u32 count;
    u8 strike;               // удар по умолчанию (cut): его делает приказ «атаковать», пока ИИ не выбрал другой
    u8 block, dodge;         // номера блока и уклона, ACTION_NONE — нет
    f32 guard;               // м: между ударами бойцы держатся на столько от цели (наибольшая досягаемость + зазор)
    const Track *walk, *run;
    u64 hash;
};

// Разобрать описание действия (формат docs/text.md, поля — docs/people.md «Обмен ударами»). Окна удара, защиты
// и отмены — из меток клипа: ставит app. false — ошибка в err
bool action_parse(const u8 *data, usize size, ActionDesc &out, char *err, usize err_size);
// Направление удара (aim) по дорожке: остриё в середине окна удара с поворотом корня клипа
Turn action_aim(const ActionDesc &a);
// Хеш чисел действия (в хеш неизменного)
u64 action_hash(const ActionDesc &a);

// Капсулы тела в мире на этот тик относительно опорной точки (её чанк и смещение): начало, конец, радиус, м
struct BodyCaps {
    f32 a[BODY_PARTS][3], b[BODY_PARTS][3], r[BODY_PARTS];
    u32 n;
};
struct World;
// Капсулы человека s относительно точки ref (дорожка действия на его тике или ходьба и бег по фазе шага)
void people_body(const World &w, u32 s, const WPos &ref, BodyCaps &out);
// Отрезок клинка человека s на тике действия t относительно ref; false — не в действии или клип без оружия
bool people_blade(const World &w, u32 s, u32 t, const WPos &ref, f32 a[3], f32 b[3]);
// Имена частей тела (по порядку дорожек)
const char *body_part_name(u32 part);
