// Намерения: игрок и ИИ выдают только их, исполняет шаг мира (docs/invariants.md, шов 3).
// Намерения игрока пишутся в запись повтора по шагам
#pragma once
#include "../core/wpos.h"

enum IntentKind : u32 {
    INTENT_NONE = 0,
    // 1–3 — намерения точек этапа 0 (убраны 2026-11-15); номера не занимать: старые записи их хранят
    INTENT_CLOCK_SET = 4,   // час дня: arg — доля суток в оборотах (2^32 — сутки), день тот же (отладка)
    INTENT_CLOCK_RATE = 5,  // ход часов: arg — тиков за шаг (отладка)
    // родить людей у target: arg — число | радиус, м << 16 | сторона << 32 | «лицом по курсу» << 40 | курс в
    // 1/256 оборота << 41 (отладка, бенч; без бита 40 курс случайный)
    INTENT_PEOPLE_SPAWN = 6,
    INTENT_GO = 7,            // идти в target: arg — номер человека | аллюр << 32 (0 шаг, 1 трусца, 2 бег)
    INTENT_ATTACK = 8,        // атаковать: arg — номер бьющего | номер цели << 32 (биться с целью, этап 11)
    INTENT_ACT = 9,           // ИИ: arg — номер бойца | (номер действия + 1) << 32; 0 — держать дистанцию
    INTENT_PLACE = 10,        // ИИ: arg — номер бойца | место вокруг цели << 32 (PLACE_* в people.h, этап 12)
};

struct Intent {
    u64 step;  // шаг, в начале которого намерение исполняется
    u32 kind;
    WPos target;
    u64 arg;   // число намерения (часы, люди); у остальных 0
};
