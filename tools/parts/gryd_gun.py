"""Штурмовая винтовка «Гриди» (docs/gryd.md): оружие машины, которое она держит двумя руками.

Оси — оси сетки в бинде (винтовка смотрит вперёд, +z), начало — кость gun в упоре приклада (GUN): поворот
винтовки — вокруг приклада, как у человека, который вскидывает и опускает оружие. Ось канала — на BORE выше упора.
Сверху вниз и сзади вперёд: скелетный приклад с затыльником, щекой и трубкой буфера; ствольная коробка (верхняя
с планкой и коллиматором, нижняя со спуском); рукоять, спусковая скоба; изогнутый магазин; рукоять заряжания;
цевьё с окнами и боковыми планками, передняя рукоять; ствол с газовым блоком и дульный тормоз с окнами.
"""
import math

from kit import Body, add
from shape import Frame, hexbolt, loft, rbox, rcyl, rlathe, rloft, rrect

GUNM, GUNP, STEEL, GLASS, LENS, FLASH = "gryd_gun", "gryd_iron", "vezha_steel", "vezha_glass", "gryd_lens", "gryd_flash"

BORE = 0.045               # ось канала над упором приклада
GRIP_R = (0.0, -0.075, 0.265)    # рукоять: точка хвата правой кисти (от упора)
GRIP_L = (0.0, -0.085, 0.57)     # передняя рукоять: хват левой кисти
LENGTH = 1.15              # до среза дульного тормоза


def _z(g, x, y, z):
    return (g[0] + x, g[1] + y, g[2] + z)


def stock(g):
    """Скелетный приклад: затыльник с резиной, верхняя тяга-щека, нижняя тяга, трубка буфера."""
    b, r = Body(), Body()
    rbox(b, _z(g, 0.0, -0.005, 0.025), (0.052, 0.17, 0.04), 0.012, GUNM)
    rbox(r, _z(g, 0.0, -0.005, 0.004), (0.056, 0.172, 0.016), 0.007, "rubber_black")
    rloft(b, Frame.look(_z(g, 0.0, 0.055, 0.03), (0, 0.06, 1.0)), [(0.0, 0.018, 0.02, 0.01, 0.0), (0.12, 0.02, 0.024, 0.011, 0.0),
                                                                  (0.2, 0.024, 0.028, 0.012, -0.004)], GUNM, n=3, end=0.008)
    rloft(b, Frame.look(_z(g, 0.0, -0.07, 0.035), (0, 0.42, 1.0)), [(0.0, 0.014, 0.014, 0.008, 0.0), (0.2, 0.014, 0.012, 0.007, 0.0)],
          GUNM, n=3, end=0.006)
    rcyl(b, _z(g, 0.0, BORE - 0.01, 0.02), (0, 0, 1), 0.017, 0.22, GUNM, e=0.004)
    for z in (0.08, 0.15):
        rcyl(b, _z(g, 0.0, BORE - 0.01, z), (0, 0, 1), 0.019, 0.008, GUNM, e=0.002)
    return b, r


def receiver(g):
    """Ствольная коробка: верхняя с окном выброса и планкой, нижняя со спуском и приёмником магазина."""
    from solid import solid
    base = Body()
    rloft(base, Frame.look(_z(g, 0.0, BORE, 0.19), (0, 0, 1)), [(0.0, 0.034, 0.036, 0.012, 0.004), (0.33, 0.034, 0.036, 0.012, 0.004)],
          None, n=3, end=0.006)
    low = Body()
    rloft(low, Frame.look(_z(g, 0.0, BORE - 0.06, 0.2), (0, 0, 1)), [(0.0, 0.03, 0.028, 0.01, 0.0), (0.27, 0.03, 0.028, 0.01, 0.0)],
          None, n=3, end=0.006)
    rbox(low, _z(g, 0.0, BORE - 0.09, 0.355), (0.062, 0.06, 0.09), 0.012, None)       # приёмник магазина
    cuts = Body()
    rbox(cuts, _z(g, 0.034, BORE + 0.006, 0.33), (0.02, 0.026, 0.085), 0.004, None)   # окно выброса справа
    for k in range(5):   # пазы облегчения слева
        rbox(cuts, _z(g, -0.035, BORE - 0.002, 0.24 + 0.04 * k), (0.012, 0.03, 0.016), 0.004, None)
    for zz in (0.215, 0.475):
        rbox(cuts, _z(g, 0.0, BORE - 0.035, zz), (0.08, 0.004, 0.004), 0.0015, None)   # шов верх / низ
    t = solid([("add", base), ("add", low), ("cut", cuts)], bevel=0.003, bevel_angle=35.0, segments=2)
    out = Body()
    out.faces = [(p, GUNM, s) for p, _, s in t.faces]
    det = Body()
    # планка сверху: основание и зубцы
    rbox(det, _z(g, 0.0, BORE + 0.042, 0.37), (0.03, 0.012, 0.34), 0.003, GUNP)
    for k in range(17):
        rbox(det, _z(g, 0.0, BORE + 0.051, 0.215 + 0.02 * k), (0.03, 0.008, 0.01), 0.002, GUNP)
    # затвор в окне выброса, рукоять заряжания слева, переводчик, болты
    rbox(det, _z(g, 0.03, BORE + 0.006, 0.33), (0.012, 0.02, 0.07), 0.003, STEEL)
    rloft(det, Frame.look(_z(g, -0.032, BORE + 0.01, 0.43), (-1, 0, 0)), [(0.0, 0.007, 0.008, 0.004, 0.0), (0.045, 0.009, 0.01, 0.005, 0.0)],
          STEEL, end=0.004)
    rcyl(det, _z(g, -0.033, BORE - 0.05, 0.265), (-1, 0, 0), 0.01, 0.006, STEEL, e=0.002)
    rbox(det, _z(g, -0.038, BORE - 0.05, 0.272), (0.004, 0.006, 0.026), 0.002, STEEL)
    for z in (0.23, 0.46):
        for sx in (-1.0, 1.0):
            hexbolt(det, _z(g, sx * 0.035, BORE - 0.045, z), (sx, 0, 0), 0.0045, 0.004, GUNP, washer=False)
    return out, det


def optic(g):
    """Коллиматор на планке: корпус-короб, окно со стеклом, бленда, крепление с винтами."""
    b, gl = Body(), Body()
    o = _z(g, 0.0, BORE + 0.09, 0.4)
    rbox(b, add(o, (0.0, -0.022, 0.0)), (0.04, 0.02, 0.1), 0.006, GUNP)
    for zz in (-0.035, 0.035):
        rloft(b, Frame.look(add(o, (0.0, 0.01, zz)), (0, 0, 1)), [(-0.006, 0.026, 0.026, 0.012, 0.0), (0.006, 0.026, 0.026, 0.012, 0.0)],
              GUNP, n=3, end=0.003)
    rloft(b, Frame.look(add(o, (0.0, 0.034, -0.035)), (0, 0, 1)), [(0.0, 0.012, 0.004, 0.003, 0.0), (0.07, 0.012, 0.004, 0.003, 0.0)],
          GUNP, end=0.003)
    for sx in (-1.0, 1.0):
        rloft(b, Frame.look(add(o, (sx * 0.022, 0.01, -0.035)), (0, 0, 1)), [(0.0, 0.004, 0.022, 0.003, 0.0), (0.07, 0.004, 0.022, 0.003, 0.0)],
              GUNP, end=0.002)
    rcyl(b, add(o, (0.025, -0.01, 0.0)), (1, 0, 0), 0.008, 0.01, GUNP, e=0.002)
    rbox(gl, add(o, (0.0, 0.01, 0.0)), (0.036, 0.04, 0.004), 0.002, GLASS)
    rcyl(gl, add(o, (0.0, 0.01, 0.0)), (0, 0, 1), 0.0015, 0.003, LENS)   # точка прицела
    for zz in (-0.03, 0.03):
        hexbolt(b, add(o, (0.022, -0.026, zz)), (1, 0, 0), 0.004, 0.004, GUNP, washer=False)
    return b, gl


def grip(g):
    """Рукоять и спусковая скоба, спусковой крючок."""
    b = Body()
    fr = Frame.look(_z(g, 0.0, BORE - 0.07, 0.285), (0, -1.0, -0.32))
    rloft(b, fr, [(0.0, 0.017, 0.024, 0.012, 0.0), (0.06, 0.019, 0.028, 0.014, 0.002), (0.12, 0.018, 0.027, 0.013, 0.0)], GUNM, n=3, end=0.01)
    b.tube([_z(g, 0.0, BORE - 0.07, 0.3), _z(g, 0.0, BORE - 0.115, 0.31), _z(g, 0.0, BORE - 0.115, 0.36), _z(g, 0.0, BORE - 0.085, 0.37)],
           0.005, GUNM, seg=10, fillet=0.012)
    rloft(b, Frame.look(_z(g, 0.0, BORE - 0.07, 0.335), (0, -1.0, 0.2)), [(0.0, 0.003, 0.006, 0.002, 0.0), (0.03, 0.003, 0.004, 0.002, -0.004)],
          STEEL, end=0.002)
    return b


def magazine(g):
    """Изогнутый магазин: короб по дуге вниз и вперёд от приёмника, рёбра по бокам, пятка."""
    b, det = Body(), Body()
    R = 0.45
    top = _z(g, 0.0, BORE - 0.1, 0.355)
    rings = []
    frames = []
    for k in range(10):
        ph = math.radians(29.0 * k / 9)
        p = (top[0], top[1] - R * math.sin(ph), top[2] + R * (1.0 - math.cos(ph)))
        f = Frame.look(p, (0.0, -math.cos(ph), math.sin(ph)), up=(0, 0, 1))
        frames.append(f)
        rings.append([f.at(0, v, u) for u, v in rrect(0.021, 0.046, 0.009, 3)])
    loft(b, rings, GUNM)
    for k in (3, 6):   # рёбра жёсткости поперёк
        f = frames[k]
        rloft(det, f.sub(-0.004, 0.0, 0.0), [(0.0, 0.024, 0.049, 0.01, 0.0), (0.008, 0.024, 0.049, 0.01, 0.0)], GUNM, n=3)
    f = frames[-1]
    rloft(det, f.sub(-0.006, 0.0, 0.0), [(0.0, 0.025, 0.052, 0.011, 0.0), (0.022, 0.025, 0.052, 0.011, 0.0)], GUNP, n=3, end=0.006)
    return b, det


def handguard(g):
    """Цевьё с окнами, боковые планки, передняя рукоять, ствол, газовый блок, дульный тормоз."""
    from solid import solid
    base = Body()
    rloft(base, Frame.look(_z(g, 0.0, BORE, 0.505), (0, 0, 1)), [(0.0, 0.034, 0.038, 0.016, 0.0), (0.33, 0.032, 0.036, 0.015, 0.0)],
          None, n=3, end=0.008)
    cuts = Body()
    for k in range(6):
        for sx in (-1.0, 1.0):
            rbox(cuts, _z(g, sx * 0.034, BORE - 0.006, 0.56 + 0.045 * k), (0.02, 0.024, 0.028), 0.008, None)
        rbox(cuts, _z(g, 0.0, BORE - 0.038, 0.56 + 0.045 * k), (0.03, 0.02, 0.026), 0.008, None)
    rcyl(cuts, _z(g, 0.0, BORE, 0.48), (0, 0, 1), 0.019, 0.4, None)
    t = solid([("add", base), ("cut", cuts)], bevel=0.0025, bevel_angle=35.0, segments=2)
    hg = Body()
    hg.faces = [(p, GUNM, s) for p, _, s in t.faces]
    det = Body()
    for sx in (-1.0, 1.0):   # боковые планки
        rbox(det, _z(g, sx * 0.037, BORE + 0.022, 0.67), (0.008, 0.012, 0.25), 0.003, GUNP)
    rbox(det, _z(g, 0.0, BORE + 0.041, 0.67), (0.028, 0.01, 0.3), 0.003, GUNP)
    for k in range(14):
        rbox(det, _z(g, 0.0, BORE + 0.048, 0.535 + 0.02 * k), (0.028, 0.007, 0.01), 0.002, GUNP)
    # передняя рукоять: стойка с рёбрами
    fr = Frame.look(_z(g, 0.0, BORE - 0.03, 0.575), (0, -1.0, 0.08))
    rloft(det, fr, [(0.0, 0.02, 0.02, 0.01, 0.0), (0.1, 0.017, 0.017, 0.008, 0.0), (0.13, 0.022, 0.022, 0.01, 0.0)], GUNP, n=3, end=0.008)
    for k in range(3):
        rcyl(det, fr.at(0.035 + 0.025 * k), fr.dir(1, 0, 0), 0.0205, 0.008, GUNP, e=0.002)
    # ствол, газовый блок с трубкой, дульный тормоз
    bar = Body()
    rlathe(bar, _z(g, 0.0, BORE, 0.48), (0, 0, 1), [(0.016, 0.0), (0.016, 0.36), (0.014, 0.37), (0.014, 0.6)], STEEL)
    rbox(det, _z(g, 0.0, BORE + 0.006, 0.89), (0.036, 0.05, 0.04), 0.008, GUNP)
    rcyl(det, _z(g, 0.0, BORE + 0.026, 0.84), (0, 0, 1), 0.007, 0.06, STEEL, e=0.002)
    brake = Body()
    bb = Body()
    rlathe(bb, _z(g, 0.0, BORE, 1.06), (0, 0, 1), [(0.016, 0.0), (0.024, 0.006), (0.024, 0.088), (0.02, 0.092)], None)
    bc = Body()
    for k in range(3):
        for sx in (-1.0, 1.0):
            rbox(bc, _z(g, sx * 0.022, BORE, 1.08 + 0.022 * k), (0.02, 0.02, 0.011), 0.004, None)
    rcyl(bc, _z(g, 0.0, BORE, 1.04), (0, 0, 1), 0.009, 0.2, None)
    t = solid([("add", bb), ("cut", bc)], bevel=0.0015, bevel_angle=35.0, segments=2)
    brake.faces = [(p, GUNP, s) for p, _, s in t.faces]
    return hg, det, bar, brake


def flash(g):
    """Вспышка выстрела (кость flash у среза тормоза): ядро, четыре языка пламени крестом и боковые выбросы из окон
    тормоза. Игра держит её сжатой в точку и раскрывает на миг выстрела."""
    b = Body()
    o = _z(g, 0.0, BORE, LENGTH)
    rlathe(b, o, (0, 0, 1), [(0.012, -0.004), (0.03, 0.02), (0.034, 0.05), (0.022, 0.09), (0.004, 0.13)], FLASH, seg=16)
    for k in range(4):
        a = math.pi / 2 * k + math.pi / 4
        d = (0.55 * math.cos(a), 0.55 * math.sin(a), 1.0)
        rlathe(b, add(o, (0.0, 0.0, 0.01)), d, [(0.012, 0.0), (0.016, 0.04), (0.009, 0.1), (0.002, 0.16)], FLASH, seg=10)
    for sx in (-1.0, 1.0):
        rlathe(b, _z(g, sx * 0.02, BORE, LENGTH - 0.05), (sx, 0.1, 0.25), [(0.008, 0.0), (0.014, 0.03), (0.008, 0.07), (0.002, 0.1)], FLASH, seg=10)
    return b


def rifle(g):
    """Все тела винтовки: [(тело, износ?)]. g — упор приклада в осях сетки."""
    st, pad = stock(g)
    rec, rdet = receiver(g)
    op, gl = optic(g)
    mag, mdet = magazine(g)
    hg, hdet, bar, brake = handguard(g)
    return [(st, True), (pad, False), (rec, True), (rdet, False), (op, False), (gl, False), (grip(g), True), (mag, True), (mdet, False),
            (hg, True), (hdet, False), (bar, False), (brake, False)]
