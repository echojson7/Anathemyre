"""Передняя нога «Вежи» (docs/vezha.md): стойка-амортизатор. Плечо от плечевого узла идёт вниз-назад к локтю, голень —
цилиндр с пружиной, из него выходит шток с копытом. Шток скользит по оси голени: пружина садится под весом и на
касании. Суставы крутят моторы в стаканах (у локтя и плеча ход больше, чем даёт поршень).

Оси рецепта — как у задней ноги (vezha_leg.py): ось поворота плечевого узла — ось y в начале координат, нога уходит
в +x, z — вбок, снаружи — −z. Локоть сгибается назад (колено вниз): нога решается как двузвенная S1, S2.
"""
import math

from kit import Body, add, mat_mul, mul, rot_z
from vezha_leg import (FOOT_H, HIP_Y, IRON, MARK, PAINT, RUBBER, STEEL, WEAR_LEG, Link, _cap, _disc, _rect, bolt)

# --- размеры, м ---
U_S = 0.075              # ось плеча — на столько дальше оси поворота
S1, S2 = 0.46, 0.72      # плечо; голень от оси локтя до оси копыта (пружина свободна)
ROD_AT = 0.43            # голова штока (кость tarsus) — на столько от локтя по оси голени
COMP_MAX = 0.07          # ход штока внутрь: пружина садится до упора
XB = 0.36                # бинд: копыто впереди оси плеча


def strut_points():
    """Суставы стойки в бинде (стоит высоко): плечо P, локоть K, голова штока R, ось копыта F."""
    P = (U_S, HIP_Y, 0.0)
    F = (U_S + XB, FOOT_H, 0.0)
    dx, dy = F[0] - P[0], F[1] - P[1]
    d = math.hypot(dx, dy)
    a = math.atan2(dy, dx) - math.acos((S1 * S1 + d * d - S2 * S2) / (2 * S1 * d))   # локоть назад
    up = Link(P, a)
    K = up.end(S1)
    s = math.atan2(F[1] - K[1], F[0] - K[0])
    lo = Link(K, s)
    return {"P": P, "K": K, "R": lo.at(ROD_AT, 0.0), "F": F, "up": up, "lo": lo, "a": a, "s": s}


def _ribs(b, link, x, z0, n, r, depth, mat=IRON):
    """Рёбра охлаждения стакана мотора вокруг оси (x, 0) звена, на боковой грани z0 в сторону −z."""
    for k in range(n):
        ang = 2 * math.pi * (k + 0.5) / n
        d = (math.cos(ang), math.sin(ang), 0.0)
        b.box(add(link.at(x, 0.0, z0), mul(link.dir(*d), r)), (0.012, 0.006, depth), mat, bevel=0.0,
              rot=mat_mul(link.m, rot_z(ang)))


def _motor(b, link, x, r, z0, length):
    """Стакан мотора сустава снаружи (−z): фланец, корпус с рёбрами, крышка с болтами."""
    b.lathe(link.at(x, 0.0, z0), (0.0, 0.0, -1.0), [(r + 0.008, 0.0), (r + 0.008, 0.01), (r, 0.014), (r, length - 0.012),
                                                    (r - 0.008, length), (r * 0.35, length + 0.004)], IRON, seg=20)
    _ribs(b, link, x, z0 - length * 0.5, 10, r + 0.002, length * 0.7)
    for k in range(6):
        ang = 2 * math.pi * (k + 0.5) / 6
        bolt(b, add(link.at(x, 0.0, z0 - length), (r * 0.6 * math.cos(ang), r * 0.6 * math.sin(ang), 0.0)), (0.0, 0.0, -1.0),
             r=0.006, h=0.005)


def hip_parts(S):
    """Плечевой узел: кулак между палубами рамы, шея вперёд и вилка оси плеча. Мотор плеча — снаружи вилки."""
    h = Body()
    h.lathe((0.0, HIP_Y - 0.07, 0.0), (0, 1, 0), [(0.05, 0.0), (0.074, 0.008), (0.074, 0.132), (0.05, 0.14)], IRON, seg=18)
    h.box((0.035, HIP_Y + 0.012, 0.0), (0.07, 0.1, 0.07), IRON, bevel=0.006)                        # шея
    P = Link(S["P"], 0.0)
    for zc in (-0.083, 0.083):                                                                       # щёки вилки
        h.loft([_rect(P, x, -0.06, 0.06, zc - 0.011, zc + 0.011) for x in (-0.06, 0.0)], IRON)
        _disc(h, P, 0.0, 0.0, zc - 0.011, zc + 0.011, 0.06, IRON, seg=18)
    h.box((0.025, HIP_Y + 0.0, 0.0), (0.04, 0.12, 0.188), IRON, bevel=0.006)                       # перемычка вилки
    _motor(h, P, 0.0, 0.058, -0.094, 0.062)
    _cap(h, P, 0.0, 1.0, 0.094, 0.042, n=6, rb=0.05)
    # разъём и шланг мотора на шее
    h.box((0.01, HIP_Y + 0.075, -0.05), (0.05, 0.03, 0.035), STEEL, bevel=0.004)
    h.tube([(0.01, HIP_Y + 0.09, -0.05), (0.04, HIP_Y + 0.1, -0.11), (U_S, HIP_Y + 0.05, -0.15)], 0.008, RUBBER, seg=6,
           fillet=0.02)
    return [(h, None)]


def upper_parts(S):
    """Плечо: две щеки и спинка-перемычка, окна облегчения; спереди — щиток в краске. Локоть — мотор снаружи."""
    from solid import solid
    up = S["up"]
    hh = lambda x: 0.062 + (0.05 - 0.062) * x / S1   # полувысота щеки
    base = Body()
    base.loft([_rect(up, x, -hh(x), -hh(x) + 0.014, -0.064, 0.064) for x in (0.08, S1 * 0.5, S1 - 0.07)], None)   # спинка сзади
    adds = Body()
    for s in (-1.0, 1.0):
        adds.loft([_rect(up, x, -hh(x), hh(x), s * 0.055 - 0.011, s * 0.055 + 0.011) for x in (0.0, S1 * 0.5, S1)], None)
        _disc(adds, up, 0.0, 0.0, s * 0.055 - 0.011, s * 0.055 + 0.011, 0.066, None, seg=20)
        _disc(adds, up, S1, 0.0, s * 0.055 - 0.011, s * 0.055 + 0.011, 0.056, None, seg=20)
    cuts = Body()
    for x, r in ((0.14, 0.026), (0.235, 0.024), (0.33, 0.02)):
        _disc(cuts, up, x, 0.006, -0.1, 0.1, r, None, seg=14)
    t = solid([("add", base), ("add", adds), ("cut", cuts)], bevel=0.004, bevel_angle=28.0)
    b = Body()
    b.faces = [(p, IRON, s) for p, _, s in t.faces]
    for s in (-1.0, 1.0):
        _disc(b, up, 0.0, 0.0, s * 0.03 - 0.019, s * 0.03 + 0.019, 0.048, STEEL, seg=14)   # втулка плеча
    _motor(b, up, S1, 0.05, -0.066, 0.05)                                               # мотор локтя
    _cap(b, up, S1, 1.0, 0.066, 0.036, n=5, rb=0.042)
    # шланг мотора локтя по внешней щеке, хомуты
    b.tube([up.at(0.06, -0.035, -0.07), up.at(0.25, -0.04, -0.072), up.at(S1 - 0.07, -0.03, -0.075)], 0.0075, RUBBER, seg=6)
    for x in (0.12, 0.3):
        b.box(up.at(x, -0.037, -0.068), (0.02, 0.026, 0.016), STEEL, bevel=0.003, rot=up.m)
    # щиток спереди: гнутый лист по передней кромке, отгибы на щёки, болты; метка — две полосы
    guard = Body()
    ring = lambda x, w, e: [up.at(x, hh(x) - 0.026, -w), up.at(x, hh(x) + 0.004, -w), up.at(x, hh(x) + 0.016 + e, -w * 0.5),
                            up.at(x, hh(x) + 0.016 + e, w * 0.5), up.at(x, hh(x) + 0.004, w), up.at(x, hh(x) - 0.026, w)]
    guard.loft([ring(0.06, 0.07, 0.0), ring(0.1, 0.09, 0.005), ring(0.3, 0.088, 0.008), ring(S1 - 0.09, 0.08, 0.003),
                ring(S1 - 0.055, 0.06, 0.0)], PAINT)
    for x in (0.13, 0.27):
        for s in (-1.0, 1.0):
            bolt(guard, up.at(x, hh(x) + 0.011, s * 0.068), up.dir(0.0, 0.84, s * 0.54), r=0.006, h=0.005)
    marks = Body()
    for k in range(2):
        x = 0.31 + 0.034 * k
        marks.box(up.at(x, hh(x) + 0.0245, 0.0), (0.015, 0.003, 0.088), MARK, bevel=0.0, rot=up.m)
    return [(b, None), (guard, WEAR_LEG), (marks, None)]


def lower_parts(S):
    """Голень: вилка локтя и цилиндр амортизатора, пружина по цилиндру между тарелями, шланг. Спереди — узкий щиток."""
    lo = S["lo"]
    b = Body()
    # вилка локтя охватывает плечо снаружи щёк
    for s in (-1.0, 1.0):
        b.loft([_rect(lo, x, -0.04, 0.04, s * 0.083 - 0.009, s * 0.083 + 0.009) for x in (0.0, 0.11)], IRON)
        _disc(b, lo, 0.0, 0.0, s * 0.083 - 0.009, s * 0.083 + 0.009, 0.05, IRON, seg=18)
    b.box(lo.at(0.115, 0.0, 0.0), (0.03, 0.08, 0.185), IRON, bevel=0.005, rot=lo.m)
    # цилиндр: стакан от вилки до горловины, кольца жёсткости
    ax = lo.dir(1.0, 0.0)
    b.lathe(lo.at(0.12, 0.0), ax, [(0.03, 0.0), (0.05, 0.012), (0.05, ROD_AT - 0.14), (0.056, ROD_AT - 0.13),
                                    (0.056, ROD_AT - 0.112), (0.036, ROD_AT - 0.1)], IRON, seg=18)
    for x in (0.2, 0.3):
        b.lathe(lo.at(x, 0.0), ax, [(0.053, 0.0), (0.053, 0.012)], IRON, seg=18)
    # пружина: тарели и витки по цилиндру
    b.lathe(lo.at(0.135, 0.0), ax, [(0.05, 0.0), (0.078, 0.0), (0.078, 0.012), (0.05, 0.012)], STEEL, seg=18)
    b.lathe(lo.at(ROD_AT - 0.03, 0.0), ax, [(0.056, 0.0), (0.08, 0.0), (0.08, 0.012), (0.056, 0.012)], STEEL, seg=18)
    n = 8
    for i in range(n):
        x = 0.16 + (ROD_AT - 0.21) * (i + 0.5) / n
        b.torus(lo.at(x, 0.0), ax, 0.066, 0.008, STEEL, seg=16, tseg=6)
    # шланг к горловине и датчик хода
    b.tube([lo.at(0.09, -0.045, -0.06), lo.at(0.2, -0.085, -0.04), lo.at(ROD_AT - 0.09, -0.07, -0.03)], 0.0075, RUBBER, seg=6,
           fillet=0.03)
    b.box(lo.at(ROD_AT - 0.08, -0.064, -0.03), (0.04, 0.022, 0.03), STEEL, bevel=0.003, rot=lo.m)
    guard = Body()
    ring = lambda x, w: [lo.at(x, 0.052, -w), lo.at(x, 0.068, -w * 0.6), lo.at(x, 0.068, w * 0.6), lo.at(x, 0.052, w)]
    guard.loft([ring(0.14, 0.04), ring(0.17, 0.05), ring(ROD_AT - 0.15, 0.05), ring(ROD_AT - 0.125, 0.038)], PAINT)
    b.box(lo.at(0.155, 0.045, 0.0), (0.02, 0.02, 0.06), IRON, bevel=0.003, rot=lo.m)
    return [(b, None), (guard, WEAR_LEG)]


def rod_parts(S):
    """Шток (кость tarsus, скользит по оси голени): хромовый шток, гофра, проушина копыта."""
    lo = S["lo"]
    ax = lo.dir(1.0, 0.0)
    b = Body()
    x0 = ROD_AT - 0.1 - COMP_MAX   # шток уходит в стакан и сжатым не торчит сверху
    b.tube([lo.at(x0, 0.0), lo.at(S2 - 0.075, 0.0)], 0.022, STEEL, seg=12)
    # гофра: манжета у горловины, складки, манжета на штоке
    g = Body()
    g.lathe(lo.at(ROD_AT - 0.105, 0.0), ax, [(0.026, 0.0), (0.034, 0.0), (0.034, 0.02), (0.026, 0.02)], RUBBER, seg=14)
    for i in range(6):
        g.torus(lo.at(ROD_AT - 0.075 + 0.025 * i, 0.0), ax, 0.03 - 0.0012 * i, 0.007, RUBBER, seg=14, tseg=5)
    g.lathe(lo.at(ROD_AT + 0.075, 0.0), ax, [(0.022, 0.0), (0.03, 0.0), (0.03, 0.018), (0.022, 0.018)], RUBBER, seg=14)
    # проушина копыта: стакан, вилка
    b.lathe(lo.at(S2 - 0.1, 0.0), ax, [(0.022, 0.0), (0.034, 0.012), (0.034, 0.05), (0.028, 0.06)], IRON, seg=14)
    for s in (-1.0, 1.0):
        b.loft([_rect(lo, x, -0.03, 0.03, s * 0.045 - 0.009, s * 0.045 + 0.009) for x in (S2 - 0.06, S2)], IRON)
        _disc(b, lo, S2, 0.0, s * 0.045 - 0.009, s * 0.045 + 0.009, 0.034, IRON, seg=14)
    return [(b, None), (g, None)]


def hoof_parts(S):
    """Копыто: шар-шарнир на оси, чашка, резиновая подошва, шипы по кругу и носок. Оси мира (подошва вниз)."""
    F = S["F"]
    H = FOOT_H
    at = lambda x, y, z=0.0: add(F, (x, y, z))
    f = Body()
    _disc(f, Link(F, 0.0), 0.0, 0.0, -0.036, 0.036, 0.026, STEEL, seg=12)
    f.lathe(at(0.0, -0.03), (0, 1, 0), [(0.02, 0.0), (0.03, 0.0), (0.03, 0.028), (0.02, 0.034)], IRON, seg=12)   # шея
    f.lathe(at(0.0, -H + 0.016), (0, 1, 0), [(0.03, 0.04), (0.06, 0.038), (0.078, 0.022), (0.084, 0.006), (0.084, 0.0),
                                             (0.03, 0.0)], IRON, seg=20)                                    # чашка
    f.lathe(at(0.0, -H), (0, 1, 0), [(0.03, 0.0), (0.086, 0.0), (0.09, 0.008), (0.088, 0.016), (0.03, 0.016)], RUBBER, seg=20)
    for k in range(6):   # шипы по кромке
        ang = 2 * math.pi * (k + 0.5) / 6
        c = at(0.078 * math.cos(ang), -H + 0.004, 0.078 * math.sin(ang))
        f.lathe(c, (0, -1, 0), [(0.009, 0.0), (0.009, 0.006), (0.003, 0.016)], STEEL, seg=6, smooth=False)
    # носок: стальной клин вперёд
    f.loft([[at(0.06, -H + 0.03, -0.022), at(0.06, -H + 0.03, 0.022), at(0.06, -H + 0.008, 0.022), at(0.06, -H + 0.008, -0.022)],
            [at(0.115, -H + 0.016, -0.012), at(0.115, -H + 0.016, 0.012), at(0.115, -H + 0.002, 0.012),
             at(0.115, -H + 0.002, -0.012)]], STEEL)
    for k in range(4):
        ang = math.pi / 4 + k * math.pi / 2
        bolt(f, at(0.05 * math.cos(ang), -H + 0.054, 0.05 * math.sin(ang)), (0, 1, 0), r=0.006, h=0.005)
    return [(f, None)]


def strut_parts(S):
    """Части стойки в осях ноги: {кость: [(тело, износ)]}. Кости — как у задней ноги, без поршня."""
    return {"hip": hip_parts(S), "thigh": upper_parts(S), "shin": lower_parts(S), "tarsus": rod_parts(S),
            "foot": hoof_parts(S)}
