"""Одноручное (ШИЛО, ЛИСТ, КОЛУН): ЗАТОЧКА, РЕЗАК, РЕССОРА, ПОЛОСА, СЕКАЧ, ТЁСЛО.

Формы — со склада беты (tools/weaponconv/onehand.py ветки stage0/test-room), переписаны на замкнутые тела без
Blender. Каждая вещь строится от торца рукояти (x = 0) к острию (+X), лезвие вниз (−Z). Функция отдаёт вещь и
кулак (x, z) в осях скрипта — там начало координат сетки.
"""
from wkit import Weapon, diamond, edge_sec, lerp, math, ring, saw, smooth


def through_hole(w, x, z, T, r):
    """Сквозное отверстие: тёмный вкладыш чуть толще полотна — видно с обеих сторон."""
    w.disc_y(x, z, 0.0, r, 2 * T + 0.0006, "hole", seg=12)


def rivets(w, x, z, T, r, mat="wire"):
    """Заклёпка насквозь: головки с обеих сторон."""
    w.dome_y(x, z, -T, r, r * 0.45, mat, side=-1)
    w.dome_y(x, z, T, r, r * 0.45, mat, side=1)


def bolt(w, x, z, T, r, mat="dark"):
    """Болт насквозь: гайка с обеих сторон."""
    w.nut_y(x, z, -T - r * 0.3, r, mat)
    w.nut_y(x, z, T + r * 0.3, r, mat)


# ================================================================ ЗАТОЧКА 0.33: напильник, сточенный в жало
def zatochka():
    w = Weapon()
    X0, L = 0.105, 0.33

    def sec(x):
        u = (x - X0) / (L - X0)
        h = 0.0095 * (1 - u ** 1.6) + 0.0004
        T = 0.0042 * (1 - u ** 1.4) + 0.0003
        return [(0, h, 0), (T, 0, 0), (0, -h, 0), (-T, 0, 0)]
    xs = [X0 + (L - X0) * (i / 40) for i in range(41)]
    w.loft(xs, sec, ["file"])
    # хвостовик, загнутый в кольцо под палец
    w.slab(-0.002, X0 + 0.004, -0.0025, 0.0025, -0.006, 0.006, "dark", bevel=0.001)
    w.torus((-0.019, 0.0, 0.0), "y", 0.018, 0.0034, "dark")
    w.wrap(0.006, X0 - 0.004, 0.0105, 0.0135, "tape", step=0.019, bulge=0.0007, n=14)
    return w, (0.055, 0.0)


# ================================================================ РЕЗАК 0.41: нож из полотна машинной пилы
def rezak():
    w = Weapon()
    X0, L = 0.12, 0.41
    H = 0.032

    def zt(x):
        return H * 0.5 + (0.0016 * saw((x - X0) / 0.0045) if x < L - 0.06 else 0.0)

    def zb(x):
        # танто: от прямой кромки косым срезом к острию у обуха
        t = (x - (L - 0.05)) / 0.05
        return -H * 0.5 + (H * 0.9 * t ** 1.05 if t > 0 else 0.0)

    def sec(x):
        top = zt(x) if x < L - 0.05 else lerp(H * 0.5, zb(x) + 0.0015, ((x - (L - 0.05)) / 0.05) ** 4)
        return edge_sec(top, zb(x), 0.0011, 0.009 if x > X0 + 0.012 else 0.0)
    # зубья обуха: по 4 станции на зуб 4.5 мм
    xs = [X0 + (L - X0) * i / 260 for i in range(261)]
    xs[-1] = L - 0.0008
    w.loft(xs, sec, ["steel", "edge"])
    through_hole(w, X0 + 0.03, 0.004, 0.0011, 0.0035)
    # рукоять: хвостовик в накладках из текстолита, две заклёпки, третью заменил болт
    gx = [0.12 * i / 12 for i in range(13)]
    w.loft(gx, lambda x: [(yy * 0.0052 / 0.016, zz + (-0.001 + 0.0015 * math.sin(x * 40)), 0)
                          for yy, zz, _ in ring(0.016, 16, 0, 0.016)], ["textolite"], shade="smooth")
    for x in (0.018, 0.06):
        rivets(w, x, 0.0, 0.0052, 0.0042)
    bolt(w, 0.1, 0.0, 0.0052, 0.0055)
    return w, (0.06, 0.0)


# ================================================================ РЕССОРА 0.9: лист рессоры
def ressora():
    w = Weapon()
    X0, L = 0.16, 0.9

    def mid(x):
        return 0.075 * ((x - X0) / (L - X0)) ** 2           # лист выгнут вверх: выпуклое лезвие снизу

    def sec(x):
        if x < X0:
            return edge_sec(0.0225, -0.0225, 0.0034, 0.0)
        u = (x - X0) / (L - X0)
        hh = lerp(0.0225, 0.019, u)
        t = (x - (L - 0.09)) / 0.09
        top = mid(x) + hh - (2 * hh * 0.9 * t ** 1.4 if t > 0 else 0)
        bot = mid(x) - hh + (0.004 * t * t if t > 0 else 0)
        T = 0.0034 * (1 - 0.3 * u) * (0.3 + 0.7 * min(1, (top - bot) / (2 * hh)))
        return edge_sec(top, bot, T, 0.015 if x > X0 + 0.02 else 0.0)
    xs = [0.02] + [X0 + (L - X0) * i / 80 for i in range(81)]
    xs[-1] = L - 0.001
    w.loft(xs, sec, ["steel", "edge"])
    # отверстие центрового болта посередине листа
    xm = X0 + 0.42
    through_hole(w, xm, mid(xm) + 0.004, 0.0030, 0.0045)
    # рукоять: гарда из обрезка листа, кожа внахлёст на деревянных щёчках, навершие-шайба
    w.slab(X0 - 0.014, X0, -0.0065, 0.0065, -0.036, 0.04, "iron", bevel=0.0025)
    w.rod(0.02, X0 - 0.014, 0.011, "wood", rz=0.0155, n=14)
    w.wrap(0.026, X0 - 0.016, 0.0118, 0.0180, "leather", step=0.016, bulge=0.0013)
    w.loft([-0.004, 0.0, 0.004, 0.02, 0.024, 0.026],
           lambda x: ring(0.0145 if x in (-0.004, 0.026) else 0.017, 16, 0, 0.017 if x in (-0.004, 0.026) else 0.02),
           ["iron"], shade="smooth")
    return w, (0.09, 0.0)


# ================================================================ ПОЛОСА 0.94: прямой обоюдоострый, к острию листом
def polosa():
    w = Weapon()
    X0, L = 0.17, 0.94

    def hw(x):
        u = (x - X0) / (L - X0)
        v = lerp(0.019, 0.017, u) + 0.006 * math.sin(math.pi * min(u / 0.85, 1)) ** 2
        t = (u - 0.8) / 0.2
        return v * (1 - t ** 1.5) + 0.0004 if t > 0 else v

    def sec(x):
        h = hw(x)
        T = 0.0028 * (0.4 + 0.6 * h / 0.025)
        return diamond(h, 0.0, -h, T, band=0.2)
    xs = [X0 + (L - X0) * (i / 70) for i in range(71)]
    xs[-1] = L - 0.0008
    w.loft(xs, sec, ["steel", "edge"])
    for z in (0.0085, -0.0085):
        rivets(w, X0 + 0.03, z, 0.0022, 0.0032, "dark")
    # гарда из обрезка уголка
    w.slab(X0 - 0.014, X0, -0.004, 0.004, -0.045, 0.045, "iron", bevel=0.001)
    w.slab(X0 - 0.014, X0 - 0.010, -0.018, -0.004, -0.045, 0.045, "iron", bevel=0.001)
    w.rod(0.02, X0 - 0.014, 0.0115, "dark", rz=0.0135)
    w.wrap(0.03, X0 - 0.016, 0.0125, 0.0148, "leather", step=0.015, bulge=0.0012)
    w.rod(0.0, 0.028, 0.019, "iron", n=6, shade="flat")   # навершие-гайка
    return w, (0.1, 0.0)


# ================================================================ СЕКАЧ 1.0: тесак из толстого листа, носок-клюв
def sekach():
    w = Weapon()
    X0, L = 0.27, 1.0

    def top(x):
        n = 0.0022 * saw((x - X0) / 0.011) if 0.04 < (x - X0) < 0.2 else 0.0     # зазубрины на обухе у пяты
        return 0.022 - n

    def bot(x):
        u = (x - X0) / (L - X0)
        z = -0.042 - 0.045 * u ** 1.3
        t = (x - (L - 0.045)) / 0.045
        if t > 0:
            z -= 0.02 * t ** 2           # нижний угол вытянут вперёд клювом
        return z

    def sec(x):
        if x < X0:
            return edge_sec(0.012, -0.012, 0.003, 0.0)
        return edge_sec(top(x), bot(x), 0.0033, 0.022 if x > X0 + 0.015 else 0.0)
    xs = [X0 - 0.12, X0 - 0.0005] + [X0 + (L - X0) * i / 180 for i in range(181)]
    w.loft(xs, sec, ["forged", "edge"])
    through_hole(w, L - 0.05, 0.004, 0.0033, 0.0075)

    # рукоять: деревянные накладки на хвостовике, три заклёпки, стальной упор у клинка, к торцу крюк
    def grip(x):
        u = (x - 0.012) / (X0 - 0.03 - 0.012)
        rz = 0.0175 + 0.0025 * math.sin(math.pi * u) + 0.007 * smooth((0.12 - u) / 0.12)
        zc = -0.003 - 0.005 * smooth((0.12 - u) / 0.12)
        return [(yy, zz + zc, m) for yy, zz, m in ring(0.0118, 18, 0, rz)]
    gx = [0.012 + (X0 - 0.03 - 0.012) * i / 30 for i in range(31)]
    w.loft(gx, grip, ["wood"], shade="smooth")
    w.slab(X0 - 0.032, X0, -0.0085, 0.0085, -0.034, 0.024, "iron", bevel=0.003)
    w.loft([0.0, 0.004, 0.009, 0.013], lambda x: [(yy, zz - 0.008, m) for yy, zz, m in
                                                 ring(0.0095 if x in (0.0, 0.013) else 0.0105, 14, 0,
                                                      0.0225 if x in (0.0, 0.013) else 0.0245)],
           ["iron"], shade="smooth")
    for x in (0.06, 0.13, 0.2):
        rivets(w, x, -0.002, 0.0117, 0.0045)
    return w, (0.17, -0.005)


# ================================================================ ТЁСЛО 0.86: топор с длинной бородой
def teslo():
    w = Weapon()
    L = 0.86
    hx = [0.0] + [L * i / 20 for i in range(1, 21)]
    w.loft(hx, lambda x: ring(0.0125 + 0.0015 * smooth(x / 0.1), 12, 0, 0.0165 + 0.002 * smooth(x / 0.1)),
           ["wood"], shade="smooth")
    w.wrap(0.012, 0.11, 0.0148, 0.0195, "cord", step=0.006, bulge=0.0009, per=4)
    # втулка из трубы
    S0, S1 = 0.735, 0.835
    w.rod(S0, S1, 0.022, "iron", rz=0.024, n=16)

    # щека-пластина: полумесяц лезвия, борода назад к рукояти
    def zt(x):
        if x < S0 + 0.01:
            return lerp(-0.13, -0.022, smooth((x - 0.6) / (S0 + 0.01 - 0.6)) ** 0.7)
        if x > S1 - 0.01:
            return lerp(-0.022, -0.06, ((x - (S1 - 0.01)) / 0.075) ** 1.5)
        return -0.022

    def zb(x):
        u = (x - 0.6) / 0.31
        return -0.135 - 0.015 * math.sin(math.pi * u) + 0.06 * max(0, u - 0.82) / 0.18

    def sec(x):
        a, b = zt(x), zb(x)
        if a - b < 0.004:
            a = b + 0.004
        return edge_sec(a, b, 0.0045, min(0.022, (a - b) * 0.5))
    xs = [0.6 + 0.305 * i / 70 for i in range(71)]
    w.loft(xs, sec, ["iron", "edge"])
    # сквозной болт и старая приварка
    bolt(w, 0.785, 0.0, 0.0225, 0.0065)
    w.tube([(S0 + 0.004, -0.0048, -0.023), (S1 - 0.004, -0.0048, -0.023)], 0.0025, "rust", seg=8)
    w.tube([(S0 + 0.004, 0.0048, -0.023), (S1 - 0.004, 0.0048, -0.023)], 0.0025, "rust", seg=8)
    return w, (0.07, 0.0)


