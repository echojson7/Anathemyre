"""Двуручное (ДВУХВАТ, ГНЁТ): ДОЛГАЯ ПОЛОСА, ОТВАЛ, БАЛКА.

Формы — со склада беты (tools/weaponconv/twohand.py ветки stage0/test-room; ОТВАЛ и БАЛКА там переделаны по
снимкам пользователя), переписаны на замкнутые тела без Blender. Гарда у x = 0, клинок к +X, рукоять к −X.
"""
from wkit import Weapon, diamond, lerp, math, ring, smooth


def hexnut(w, x0, x1, r, mat):
    w.rod(x0, x1, r, mat, n=6, shade="flat")


# ================================================================ ДОЛГАЯ ПОЛОСА: 1.3 м, клинок на полторы руки
def dolgaya():
    w = Weapon()
    BL = 1.0          # от гарды до острия
    RIC = 0.13        # незаточенная пята

    def hw(x):        # полуширина клинка
        return lerp(0.026, 0.018, x / BL)

    def sec(x):
        h = hw(x)
        # остриё срезано наискось: верхняя кромка сходит вниз за последние 9 см
        t = (x - (BL - 0.09)) / 0.09
        zt = h - (2 * h * 0.92) * max(0.0, t) ** 1.1
        zb = -h + 0.004 * max(0.0, t) ** 2
        zr = (zt + zb) / 2
        T = 0.0034 * (1 - 0.35 * x / BL) * (0.25 + 0.75 * (zt - zb) / (2 * h))
        return diamond(zt, zr, zb, max(T, 0.0005), band=0.0 if x < RIC else 0.22)
    xs = [0.0, RIC - 0.001, RIC] + [RIC + (BL - 0.09 - RIC) * i / 30 for i in range(1, 31)] + \
         [BL - 0.09 + 0.09 * (i / 14) for i in range(1, 14)] + [BL - 0.0008]
    # у пяты у сечения нет заточки, дальше есть: число точек сечения разное — пята отдельным телом
    w.loft(xs[:2], sec, ["steel", "edge"])
    w.loft(xs[1:], lambda x: sec(max(x, RIC)), ["steel", "edge"])
    # усы перехвата в конце пяты: два шипа из той же полосы
    for sgn in (1, -1):
        def lug(x, sgn=sgn):
            k = lerp(0.0, 0.009, (x - RIC + 0.016) / 0.016)
            a, b = sgn * (hw(x) + k), sgn * (hw(x) - 0.004)
            top, bot = max(a, b), min(a, b)
            return [(-0.003, top, 0), (0.003, top, 0), (0.003, bot, 0), (-0.003, bot, 0)]
        w.loft([RIC - 0.016 + 0.016 * i / 6 for i in range(7)], lug, ["steel"])
    # кожаная обмотка на пяте под перехват
    w.wrap(0.012, RIC - 0.028, 0.006, 0.029, "leather", step=0.012, bulge=0.001, n=16)
    # гарда: прямой брусок
    w.slab(-0.018, 0.0, -0.011, 0.011, -0.075, 0.075, "iron", bevel=0.003)
    # рукоять: кожа внахлёст, навершие — две гайки
    w.rod(-0.31, -0.018, 0.014, "dark", rz=0.017)
    w.wrap(-0.285, -0.022, 0.0155, 0.0185, "leather", step=0.017, bulge=0.0016)
    hexnut(w, -0.312, -0.288, 0.024, "iron")
    hexnut(w, -0.338, -0.314, 0.021, "iron")
    return w, (-0.07, 0.0)


# ================================================================ ОТВАЛ: широкий тяжёлый клинок, корпус-гарда, 1.65 м
def otval():
    w = Weapon()
    BL, H, T = 1.2, 0.085, 0.0095     # длина клинка, полуширина, полутолщина обуха
    TL = 0.27                          # длина скоса к острию

    def sec(x):
        t = max(0.0, (x - (BL - TL)) / TL)
        zt = H - 0.004 * t                                 # обух прямой до острия
        zb = lerp(-H, zt - 0.003, t ** 1.08)               # лезвие уходит косой линией к острию у обуха
        hgt = zt - zb
        zf = zt - hgt * 0.42                               # плоскость, ниже неё широкий спуск
        tt = T * (1 - 0.88 * t)
        zbn = zb + min(0.012, hgt * 0.15)                  # подводка
        ee = 0.0005
        return [(-tt, zt, 0), (tt, zt, 0), (tt, zf, 0), (0.0018, zbn, 1), (ee, zb, 0),
                (-ee, zb, 1), (-0.0018, zbn, 0), (-tt, zf, 0)]
    xs = [0.0] + [(BL - TL) * i / 30 for i in range(1, 31)] + [BL - TL + TL * i / 30 for i in range(1, 30)] + [BL - 0.001]
    w.loft(xs, sec, ["forged", "edge"])
    # корпус-гарда: брусок со скруглёнными углами, болт с куполом
    w.boxc((-0.036, 0.0, 0.0), (0.06, 0.062, 0.244), "iron", bevel=0.01)
    # прижимная планка между корпусом и клинком, с прорезями с обеих сторон
    w.slab(-0.008, 0.0, -0.034, 0.034, -0.118, 0.118, "dark", bevel=0.0015)
    for k in range(7):
        z = -0.09 + k * 0.03
        w.boxc((-0.004, 0.0, z), (0.009, 0.0695, 0.006), "hole", bevel=0.0)
    for side in (-1, 1):
        w.disc_y(-0.036, 0.06, side * 0.0315, 0.0145, 0.003, "dark", seg=20)
        w.dome_y(-0.036, 0.06, side * 0.032, 0.012, 0.006, "dark", side=side, seg=16)
    # рукоять: стержень с кольцами, навершие-стакан
    w.rod(-0.45, -0.066, 0.0165, "iron", n=18)
    for k in range(9):
        x = -0.43 + k * 0.042
        w.loft([x, x + 0.001, x + 0.005, x + 0.006], lambda xx, x=x: ring(0.0178 if xx in (x, x + 0.006) else 0.0188, 18, 0),
               ["dark"], shade="smooth")
    w.loft([-0.5, -0.497, -0.462, -0.458, -0.45],
           lambda x: ring({-0.5: 0.0205, -0.497: 0.022, -0.462: 0.022, -0.458: 0.019, -0.45: 0.019}[x], 16, 0),
           ["iron"], shade="smooth")
    return w, (-0.12, 0.0)


# ================================================================ БАЛКА: длинный клинок с долом и загнутым концом, витая гарда, 1.4 м
def balka():
    w = Weapon()
    BL = 1.0
    H = 0.032
    T = 0.0048

    def drop(x):
        # конец клинка загибается к лезвию: последние 22 см идут дугой вниз
        t = max(0.0, (x - (BL - 0.22)) / 0.22)
        return 0.075 * t ** 2.2

    def sec(x):
        u = x / BL
        hh = lerp(H, H * 0.9, u)
        t = max(0.0, (x - (BL - 0.07)) / 0.07)
        zt = hh - drop(x) - (2 * hh * 0.97 * t ** 1.3)          # обух у кончика скруглён вниз к острию
        zb = -hh - drop(x) - 0.004 * math.sin(math.pi * min(1, t))
        if zt - zb < 0.0015:
            zt = zb + 0.0015
        hgt = zt - zb
        tt = T * (1 - 0.45 * u) * min(1.0, hgt / (2 * hh) + 0.25)
        # дол: от пяты почти до конца, идёт за изгибом
        fd = 0.0 if not (0.03 < x < BL - 0.09) else 0.0022 * min(1, (x - 0.03) / 0.03, (BL - 0.09 - x) / 0.03)
        zf1, zf2 = zt - hgt * 0.22, zt - hgt * 0.42
        zbev = zb + hgt * 0.3
        e = 0.0005
        f = [(tt, zt, 0), (tt, zf1, 0), (tt - fd, zf1 - 0.002, 0), (tt - fd, zf2 + 0.002, 0), (tt, zf2, 0),
             (tt, zbev, 1), (e, zb, 1)]
        back = [(-y, z, 0) for y, z, _ in reversed(f)]
        return [(-tt, zt, 0)] + f + back[1:-1]
    xs = [0.0] + [BL * i / 120 for i in range(1, 120)] + [BL - 0.0008]
    w.loft(xs, sec, ["forged", "edge"])
    # гарда: витой квадратный пруток, сделан вдоль X и поставлен поперёк (по Z)
    GH = 0.1
    m = w.mark()

    def gsec(x):
        a = x / GH * math.pi * 7
        s = 0.0085 * 1.41
        return [(s * math.cos(a + k * math.pi / 2), s * math.sin(a + k * math.pi / 2), 0) for k in range(4)]
    w.loft([-GH + 2 * GH * i / 120 for i in range(121)], gsec, ["forged"], shade="strips")
    w.apply(m, lambda p: (p[2] - 0.008, p[1], -p[0]))
    # муфта на гарде и широкий лопатообразный хвостовик над ней
    w.slab(-0.016, 0.0, -0.012, 0.012, -0.022, 0.022, "dark", bevel=0.0015)

    def ric(x):
        u = (x + 0.016) / -0.1
        return ring(lerp(0.008, 0.012, u), 16, 0, lerp(0.03, 0.014, smooth(u)))
    w.loft([-0.116 + 0.1 * i / 20 for i in range(21)], ric, ["iron"], shade="smooth")
    w.rod(-0.33, -0.11, 0.0125, "dark", rz=0.0145, n=14)
    w.wrap(-0.32, -0.115, 0.0135, 0.0155, "leather", step=0.022, bulge=0.0014)
    # навершие-колесо с отверстием
    w.disc_y(-0.355, 0.0, 0.0, 0.027, 0.02, "iron", seg=28)
    w.disc_y(-0.355, 0.0, 0.0, 0.0095, 0.0206, "hole", seg=20)
    w.rod(-0.335, -0.318, 0.011, "dark", rz=0.014)
    return w, (-0.15, 0.0)


